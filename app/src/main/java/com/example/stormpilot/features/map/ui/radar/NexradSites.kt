internal data class NexradSite(
    val id: String,
    val latitude: Double,
    val longitude: Double,
)

internal fun nexradSitesGeoJson(sites: List<NexradSite>): String {
    val features = sites.joinToString(",") { site ->
        """
        {
          "type": "Feature",
          "geometry": {
            "type": "Point",
            "coordinates": [${site.longitude}, ${site.latitude}]
          },
          "properties": {
            "id": "${site.id}"
          }
        }
        """.trimIndent()
    }
    return """{"type":"FeatureCollection","features":[$features]}"""
}

